"""
Constants for Availo platform.
Defines full 14-state machine and state transitions for bookings.
"""

class BookingStatus:
    DRAFT = "DRAFT"
    PENDING_APPROVAL = "PENDING_APPROVAL"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    WAITLISTED = "WAITLISTED"
    AWAITING_SIGNATURES = "AWAITING_SIGNATURES"
    AWAITING_PAYMENT = "AWAITING_PAYMENT"
    CONFIRMED = "CONFIRMED"
    CHECKED_IN = "CHECKED_IN"
    RETURN_SUBMITTED = "RETURN_SUBMITTED"
    DAMAGE_REVIEW = "DAMAGE_REVIEW"
    COMPLETED = "COMPLETED"
    DISPUTE_OPEN = "DISPUTE_OPEN"
    RESOLVED_OWNER = "RESOLVED_OWNER"
    RESOLVED_USER = "RESOLVED_USER"
    RESOLVED_SPLIT = "RESOLVED_SPLIT"
    CANCELLED = "CANCELLED"

    # Valid transitions (state machine guard)
    TRANSITIONS = {
        DRAFT: [PENDING_APPROVAL, CANCELLED],
        PENDING_APPROVAL: [APPROVED, REJECTED, WAITLISTED, CANCELLED],
        APPROVED: [AWAITING_SIGNATURES, CANCELLED],
        WAITLISTED: [PENDING_APPROVAL, CANCELLED],
        AWAITING_SIGNATURES: [AWAITING_PAYMENT, CANCELLED],
        AWAITING_PAYMENT: [CONFIRMED, CANCELLED],
        CONFIRMED: [CHECKED_IN, CANCELLED],
        CHECKED_IN: [RETURN_SUBMITTED],
        RETURN_SUBMITTED: [DAMAGE_REVIEW, COMPLETED],
        DAMAGE_REVIEW: [DISPUTE_OPEN, COMPLETED],
        DISPUTE_OPEN: [RESOLVED_OWNER, RESOLVED_USER, RESOLVED_SPLIT],
    }

    @staticmethod
    def can_transition(from_state: str, to_state: str) -> bool:
        return to_state in BookingStatus.TRANSITIONS.get(from_state, [])
